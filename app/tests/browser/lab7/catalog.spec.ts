import { expect, test } from '@playwright/test'
import { catalogTitles, expectCatalog, openCatalog, readPlan, titles } from './support'

test.use({ storageState: { cookies: [], origins: [] } })

test('R1-01 search, compatible filters, empty state, individual removal and reset', async ({ page }) => {
  await openCatalog(page)
  await expectCatalog(page, catalogTitles)
  await page.getByLabel('Поиск по каталогу', { exact: true }).fill('акварель')
  await expectCatalog(page, [titles.art])
  await page.getByRole('button', { name: 'Очистить поиск', exact: true }).click()
  await expectCatalog(page, catalogTitles)

  await page.getByLabel('Поиск по каталогу', { exact: true }).fill('учебная')
  await page.getByRole('group', { name: 'Направление', exact: true }).getByRole('checkbox', { name: 'Творчество', exact: true }).check()
  await page.getByRole('group', { name: 'Район', exact: true }).getByRole('checkbox', { name: 'Кировский', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Понедельник', exact: true }).check()
  await page.getByLabel('Начало занятия с', { exact: true }).fill('10:00')
  await page.getByLabel('Начало занятия до', { exact: true }).fill('11:59')
  await page.getByLabel('Формат', { exact: true }).selectOption({ label: 'Очно' })
  await page.getByLabel('Бюджет в месяц', { exact: true }).selectOption('5000')
  await page.getByLabel('Лифт', { exact: true }).selectOption('no')
  await page.getByLabel('Вход без ступеней', { exact: true }).selectOption('no')
  await expectCatalog(page, [titles.art, titles.gap29])
  await page.getByLabel('Бюджет в месяц', { exact: true }).selectOption('0')
  await expectCatalog(page, [titles.art])

  await page.getByLabel('Поиск по каталогу', { exact: true }).fill('несуществующиймаркерлр7')
  await expectCatalog(page, [])
  await expect(page.getByRole('heading', { name: 'По этим условиям занятий нет', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Убрать фильтр: Поиск: несуществующиймаркерлр7', exact: true }).click()
  await expectCatalog(page, [titles.art])
  await expect(page.getByLabel('Поиск по каталогу', { exact: true })).toHaveValue('')
  await expect(page.getByRole('checkbox', { name: 'Кировский', exact: true })).toBeChecked()
  await expect(page.getByLabel('Бюджет в месяц', { exact: true })).toHaveValue('0')
  await expect(page.getByLabel('Начало занятия с', { exact: true })).toHaveValue('10:00')

  await page.getByRole('button', { name: 'Сбросить всё', exact: true }).click()
  await expectCatalog(page, catalogTitles)
  await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(0)
  await expect(page.getByLabel('Бюджет в месяц', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Формат', { exact: true })).toHaveValue('any')
  await expect(page.getByLabel('Лифт', { exact: true })).toHaveValue('any')
  await expect(page.getByLabel('Вход без ступеней', { exact: true })).toHaveValue('any')
  await expect(page.getByLabel('Начало занятия с', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Начало занятия до', { exact: true })).toHaveValue('')
  await expect.poll(() => readPlan(page)).toMatchObject({ activityIds: [], monthlyBudget: null })
})

test('R1-02 area and text search keep eligible pure online groups in stable order', async ({ page }) => {
  await openCatalog(page)
  await page.getByRole('checkbox', { name: 'Академический', exact: true }).check()
  await page.getByLabel('Поиск по каталогу', { exact: true }).fill('учебная')
  await page.getByLabel('Бюджет в месяц', { exact: true }).selectOption('5000')
  await expectCatalog(page, [titles.gap30, titles.hybrid, titles.online])
  await page.getByLabel('Формат', { exact: true }).selectOption({ label: 'Онлайн' })
  await expectCatalog(page, [titles.hybrid, titles.online])
  await page.getByLabel('Поиск по каталогу', { exact: true }).fill('цифровые')
  await expectCatalog(page, [titles.online])
})
