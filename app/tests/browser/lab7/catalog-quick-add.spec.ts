import { expect, test } from '@playwright/test'
import { openCatalog, readPlan, titles } from './support'

test.use({ storageState: { cookies: [], origins: [] } })

for (const width of [375, 768, 1280]) {
  test(`quick add, persistence, removal, Undo and card layout at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await openCatalog(page)
    const search = page.getByLabel('Поиск по каталогу', { exact: true })
    await search.fill('ходьба')
    await page.getByLabel('Формат', { exact: true }).selectOption({ label: 'Очно' })
    const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: titles.walk, exact: true }) })
    const details = card.getByRole('link', { name: /Подробнее/ })
    const add = card.getByRole('button', { name: `Добавить в план: ${titles.walk}`, exact: true })
    await add.scrollIntoViewIfNeeded()
    const before = await page.evaluate(() => window.scrollY)
    await details.focus()
    await page.keyboard.press('Tab')
    await expect(add).toBeFocused()
    const boxes = [await details.boundingBox(), await add.boundingBox()]
    const [a, b] = boxes
    expect(a).not.toBeNull(); expect(b).not.toBeNull()
    if (!a || !b) throw new Error('Missing card actions')
    expect(a.x + a.width <= b.x || b.x + b.width <= a.x || a.y + a.height <= b.y || b.y + b.height <= a.y).toBe(true)
    expect(a.height).toBeGreaterThanOrEqual(44)
    expect(b.height).toBeGreaterThanOrEqual(44)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL('/activities')
    const selected = card.getByRole('button', { name: `В плане ✓: ${titles.walk}`, exact: true })
    await expect(selected).toBeDisabled()
    await expect(search).toHaveValue('ходьба')
    await expect(page.getByLabel('Формат', { exact: true })).toHaveValue('offline')
    expect(await page.evaluate(() => window.scrollY)).toBeCloseTo(before, 0)
    await expect.poll(() => readPlan(page)).toMatchObject({ activityIds: ['group-walk'], estimatedMonthlyTotal: 4000 })
    await selected.dispatchEvent('click')
    await expect.poll(() => readPlan(page)).toMatchObject({ activityIds: ['group-walk'], estimatedMonthlyTotal: 4000 })
    await details.click()
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(titles.walk)
    await expect(page.getByRole('button', { name: 'Уже в плане', exact: true })).toBeDisabled()
    await page.getByRole('link', { name: 'Мой план', exact: true }).click()
    const selectedGroups = page.getByRole('region', { name: 'Выбранные занятия', exact: true })
    await expect(selectedGroups.getByRole('heading', { level: 3 })).toHaveText([titles.walk])
    await page.reload()
    await expect(selectedGroups.getByRole('heading', { level: 3 })).toHaveText([titles.walk])
    await page.getByRole('link', { name: 'Добавить ещё', exact: true }).click()
    await expect(selected).toBeDisabled()
    await page.reload()
    await expect(selected).toBeDisabled()
    await page.getByRole('link', { name: 'Мой план', exact: true }).click()
    await page.getByRole('button', { name: `Удалить из плана: ${titles.walk}`, exact: true }).click()
    await page.getByRole('link', { name: 'Найти занятия', exact: true }).click()
    await expect(add).toBeEnabled()
    await page.getByRole('link', { name: 'Мой план', exact: true }).click()
    await page.getByRole('button', { name: 'Отменить удаление', exact: true }).click()
    await page.getByRole('link', { name: 'Добавить ещё', exact: true }).click()
    await expect(selected).toBeDisabled()
    await expect.poll(() => readPlan(page)).toMatchObject({ activityIds: ['group-walk'], estimatedMonthlyTotal: 4000 })
  })
}
