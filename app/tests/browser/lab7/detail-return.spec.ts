import { expect, test } from '@playwright/test'
import { openCatalog, readPlan, titles } from './support'

test.use({ storageState: { cookies: [], origins: [] } })

test('UX-04 catalog return keeps search, filters and existing detail addition', async ({ page }) => {
  await openCatalog(page)
  await page.getByLabel('Поиск по каталогу', { exact: true }).fill('ходьба')
  await page.getByLabel('Формат', { exact: true }).selectOption('offline')
  await page.getByRole('article').getByRole('link', { name: /Подробнее/ }).click()
  const back = page.getByRole('link', { name: '← Вернуться в каталог', exact: true })
  await expect(back).toHaveAttribute('href', '/activities')
  await expect(page.getByRole('link', { name: '← Вернуться в мой план', exact: true })).toHaveCount(0)
  await back.focus()
  await expect(back).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL('/activities')
  await expect(page.getByLabel('Поиск по каталогу', { exact: true })).toHaveValue('ходьба')
  await expect(page.getByLabel('Формат', { exact: true })).toHaveValue('offline')
  await page.getByRole('article').getByRole('link', { name: /Подробнее/ }).click()
  await page.getByRole('button', { name: 'Добавить в мой план', exact: true }).click()
  await expect(page).toHaveURL('/activity-added')
  await expect.poll(() => readPlan(page)).toMatchObject({ activityIds: ['group-walk'], estimatedMonthlyTotal: 4000 })
})

test('UX-04 selected card and weekly schedule return to plan; reload falls back to catalog', async ({ page }) => {
  await openCatalog(page)
  await page.getByRole('button', { name: `Добавить в план: ${titles.walk}`, exact: true }).click()
  await page.getByRole('link', { name: 'В мой план', exact: true }).click()
  const selected = page.getByRole('region', { name: 'Выбранные занятия', exact: true })
  await selected.getByRole('link', { name: /Подробнее/ }).click()
  const back = page.getByRole('link', { name: '← Вернуться в мой план', exact: true })
  await expect(back).toHaveAttribute('href', '/my-plan')
  await expect(page.getByRole('button', { name: 'Уже в плане', exact: true })).toBeDisabled()
  await back.focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL('/my-plan')
  await page.getByRole('region', { name: 'Расписание на неделю', exact: true }).getByRole('link', { name: titles.walk, exact: true }).first().click()
  await expect(back).toBeVisible()
  await page.reload()
  await expect(back).toHaveCount(0)
  const catalog = page.getByRole('link', { name: '← Вернуться в каталог', exact: true })
  await expect(catalog).toHaveAttribute('href', '/activities')
  await expect(page.getByRole('button', { name: 'Уже в плане', exact: true })).toBeDisabled()
  await expect.poll(() => readPlan(page)).toMatchObject({ activityIds: ['group-walk'], estimatedMonthlyTotal: 4000 })
  await catalog.click()
  await expect(page).toHaveURL('/activities')
})

test('UX-04 direct detail URL has a safe catalog return before and after reload', async ({ page }) => {
  await page.goto('/activities/group-walk')
  const back = page.getByRole('link', { name: '← Вернуться в каталог', exact: true })
  await expect(back).toHaveAttribute('href', '/activities')
  await page.reload()
  await expect(back).toBeVisible()
  await back.click()
  await expect(page).toHaveURL('/activities')
})
